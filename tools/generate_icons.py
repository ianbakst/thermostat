#!/usr/bin/env python3
"""
Regenerates the UI's icon fonts from Material Design Icons, the icon set Home
Assistant uses (https://pictogrammers.com/library/mdi/).

    python3 tools/generate_icons.py      (from the project root; needs Node.js)

LVGL can't read icon files at runtime, so the icons we use are converted into
an LVGL font (a C file of pre-rendered glyphs) by LVGL's lv_font_conv tool.
The tool and the icon font are downloaded into a temporary folder; only the
generated files in src/ui/icons/ are kept.

To add an icon: add it to ICONS, re-run, and use ICON_<NAME> from icons.h.
"""

import pathlib
import re
import subprocess
import tempfile

LV_FONT_CONV_VERSION = "1.5.3"
MDI_VERSION = "7.4.47"  # icons and fonts are Apache 2.0 licensed

# One font per size (icons are pre-rendered, so each size is its own font).
SIZES_PX = [24, 32, 40]
BPP = 4  # 16 levels of anti-aliasing

# (MDI icon name, what it's for)
ICONS = [
    ("power", "mode: off"),
    ("fire", "mode: heat"),
    ("snowflake", "mode: cool"),
    ("sun-snowflake-variant", "mode: auto"),
    ("water-percent", "mode: dry"),
    ("fan", "mode: fan only"),
    ("fan-speed-1", "fan: low"),
    ("fan-speed-2", "fan: medium"),
    ("fan-speed-3", "fan: high"),
    ("fan-auto", "fan: auto"),
    ("fan-off", "fan: off"),
    ("weather-windy", "fan: ambient"),
    ("cog", "settings button"),
    ("triangle", "setpoint up"),
    ("triangle-down", "setpoint down"),
    ("close", "close settings"),
]

# MDI codepoints are above U+FFFF (4-byte UTF-8). Remap them into the Unicode
# Private Use Area from U+E000 so each icon is a short 3-byte string.
FIRST_CODEPOINT = 0xE000

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT_DIR = ROOT / "src" / "ui" / "icons"


def utf8_literal(codepoint: int) -> str:
    return "".join(f"\\x{b:02X}" for b in chr(codepoint).encode("utf-8"))


def main() -> None:
    with tempfile.TemporaryDirectory() as tmp:
        subprocess.run(
            ["npm", "install", "--prefix", tmp, "--silent",
             f"lv_font_conv@{LV_FONT_CONV_VERSION}", f"@mdi/font@{MDI_VERSION}"],
            check=True,
        )
        mdi = pathlib.Path(tmp) / "node_modules" / "@mdi" / "font"
        variables = (mdi / "scss" / "_variables.scss").read_text()

        ranges = []
        defines = []
        for i, (name, purpose) in enumerate(ICONS):
            match = re.search(rf'^\s+"{re.escape(name)}": ([0-9A-F]+),$', variables, re.MULTILINE)
            if not match:
                raise SystemExit(f"Unknown MDI icon: {name}")
            source = int(match.group(1), 16)
            target = FIRST_CODEPOINT + i
            ranges += ["-r", f"0x{source:X}=>0x{target:X}"]
            macro = "ICON_" + name.upper().replace("-", "_")
            defines.append(f'#define {macro:<28} "{utf8_literal(target)}"  // mdi:{name} ({purpose})')

        OUT_DIR.mkdir(parents=True, exist_ok=True)
        for old in OUT_DIR.glob("mdi_icons_*.c"):
            old.unlink()  # drop sizes no longer listed

        for size in SIZES_PX:
            font_name = f"mdi_icons_{size}"
            font_c = OUT_DIR / f"{font_name}.c"
            subprocess.run(
                [str(pathlib.Path(tmp) / "node_modules" / ".bin" / "lv_font_conv"),
                 "--font", str(mdi / "fonts" / "materialdesignicons-webfont.ttf"), *ranges,
                 "--size", str(size), "--bpp", str(BPP), "--format", "lvgl",
                 "--no-compress", "--lv-include", "lvgl.h", "--lv-font-name", font_name,
                 "-o", str(font_c)],
                check=True,
            )

            # The generated file's header records the command line; drop the
            # machine-specific temp and project paths so regenerating is repeatable.
            font_c.write_text(
                font_c.read_text()
                .replace(str(mdi / "fonts") + "/", "")
                .replace(str(OUT_DIR) + "/", "")
            )

    header = "\n".join([
        "#pragma once",
        "//",
        "// Icons from Material Design Icons (Apache 2.0), as LVGL fonts.",
        "// GENERATED by tools/generate_icons.py; edit that script, not this file.",
        "//",
        "// Use an icon as label text with one of the icon fonts, e.g.",
        f"//   lv_obj_set_style_text_font(label, &mdi_icons_{SIZES_PX[0]}, 0);",
        "//   lv_label_set_text(label, ICON_FIRE);",
        "//",
        "",
        "#include <lvgl.h>",
        "",
        *[f"LV_FONT_DECLARE(mdi_icons_{size})  // {size}px" for size in SIZES_PX],
        "",
        *defines,
        "",
    ])
    (OUT_DIR / "icons.h").write_text(header)
    print(f"Wrote {len(ICONS)} icons to {OUT_DIR.relative_to(ROOT)}/")


if __name__ == "__main__":
    main()
